import type { Project } from '../types/project';

export function buildPackScript(project: Project): string {
  const slug = project.meta.slug;
  const hasLyrics = project.layers.some((l) => l.type === 'lyrics');
  return [
    '#!/usr/bin/env python3',
    `"""Pack '${project.meta.title}' into a signed .spectralis capsule (SPCC v3). Generated by`,
    'tools/visualizer-studio — fill in your audio file and confirm entries before running."""',
    'import base64, hashlib, io, json, os, sys, zipfile',
    'from pathlib import Path',
    'from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey',
    '',
    'ROOT = Path(__file__).parent',
    `OUTPUT_PATH = ROOT / "${slug}.spectralis"`,
    '# Fill these in to match your registered signing key (see other metadata/*/pack_*.py for examples):',
    'EXPECTED_FINGERPRINT = "FILL-IN"',
    'KEY_ID = "FILL-IN"',
    'KEY_CANDIDATES = [',
    '    os.environ.get("SPECTRALIS_PRIVATE_KEY_PATH"),',
    '    str(Path.home() / ".spectralis" / "keys" / f"{KEY_ID}.pem"),',
    ']',
    '',
    'def resolve_private_key_path():',
    '    for candidate in KEY_CANDIDATES:',
    '        if not candidate: continue',
    '        p = Path(candidate)',
    '        if p.exists(): return p',
    '    sys.exit("Signing key not found. Set SPECTRALIS_PRIVATE_KEY_PATH or place it under ~/.spectralis/keys/")',
    '',
    'def load_private_key(path):',
    '    raw = path.read_bytes()',
    '    if raw.lstrip().startswith(b"-----BEGIN"):',
    '        from cryptography.hazmat.primitives.serialization import load_pem_private_key',
    '        return load_pem_private_key(raw, password=None), KEY_ID',
    '    doc = json.loads(raw.decode("utf-8-sig"))',
    '    return Ed25519PrivateKey.from_private_bytes(base64.b64decode(doc["privateKeySeedBase64"])), doc["keyId"]',
    '',
    'private_key, key_id = load_private_key(resolve_private_key_path())',
    'pub_bytes = private_key.public_key().public_bytes_raw()',
    'fingerprint = hashlib.sha256(pub_bytes).hexdigest()',
    'print(f"Key: {key_id}  Fingerprint: {fingerprint}")',
    '',
    'ENTRIES = [',
    `    ("assets/data/${slug}_module.json", ROOT / "${slug}_module.json"),`,
    `    ("assets/html/${slug}_visualizer.html", ROOT / "${slug}_visualizer.html"),`,
    hasLyrics ? `    ("assets/data/${slug}.lrc", ROOT / "${slug}.lrc"),` : '    # no LRC layer in this project',
    `    ("audio/${slug}.wav", ROOT / "${slug}.wav"),  # swap extension/path to match your actual audio file`,
    `    ("manifest.json", ROOT / "${slug}_manifest.json"),`,
    `    ("reactive.json", ROOT / "${slug}_reactive.json"),`,
    ']',
    'for _, src in ENTRIES:',
    '    if not src.exists(): sys.exit(f"Missing: {src}")',
    '',
    'buf = io.BytesIO()',
    'with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zf:',
    '    for name, src in ENTRIES: zf.write(src, name)',
    'payload = buf.getvalue()',
    'signature = private_key.sign(payload)',
    'header = bytearray(104)',
    'header[0:4] = b"SPCC"',
    'header[4:8] = (3).to_bytes(4, "little")',
    'header[8:40] = pub_bytes',
    'header[40:104] = signature',
    'OUTPUT_PATH.write_bytes(bytes(header) + payload)',
    'print(f"Wrote {OUTPUT_PATH} ({OUTPUT_PATH.stat().st_size:,} bytes)")',
    '',
  ].join('\n');
}
